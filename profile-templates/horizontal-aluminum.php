        var allSelected = true;

        // Find all headers for this group
        $('.profile-accordion-header[data-group="' + group + '"]').each(function() {
            var hasSelection = $(this).next('.profile-accordion-content').find('.option-box.selected').length > 0;
            if (!hasSelection) {
                allSelected = false;
            }
        });

        // Show/hide buttons based on completion
        if (allSelected) {
            $('.' + group + '-buttons').css('display', 'block');
            console.log('Showing buttons for group:', group);
        } else {
            $('.' + group + '-buttons').css('display', 'none');
            console.log('Hiding buttons for group:', group);
        }

        console.log('Group ' + group + ' complete:', allSelected);
    }

    // Semi-Privacy: Populate BODY based on GAP selection
    $(document).on('click', '.sp-gap-option', function(e) {
        var gapValue = $(this).data('value');
        var bodyContent = $('.sp-body-content');

        console.log('Semi-Privacy GAP selected:', gapValue);

        var bodyOptions = {
            '1-2': ['35-1-2', '39-1-2', '43-1-2', '47-1-2', '51-1-2', '55-1-2', '59-1-2', '63-1-2', '67-1-2', '71-1-2', '75-1-2', '79-1-2', '83-1-2', '87-1-2', '91-1-2', '95-1-2', '99-1-2', '103-1-2', '107-1-2', '111-1-2', '115-1-2', '119-1-2'],
            '1': ['35', '39-1-2', '44', '48-1-2', '53', '57-1-2', '62', '66-1-2', '71', '75-1-2', '80-1-2', '84-1-2', '89', '93-1-2', '98', '102-1-2', '107', '111-1-2', '116'],
            '1-3-8': ['37-5-8', '42-1-2', '47-3-8', '52-1-4', '57-1-8', '62', '66-7-8', '71-3-4', '76-5-8', '81-1-2', '86-3-8', '91-1-4', '96-1-8', '101', '105-7-8', '110-3-4', '115-5-8']
        };

        var options = bodyOptions[gapValue] || [];
        bodyContent.empty();

        if (options.length > 0) {
            options.forEach(function(val) {
                // Convert "35-1-2" to "35 1/2" format
                var parts = val.split('-');
                var displayVal = parts[0]; // Start with the whole number
                if (parts.length > 1) {
                    // Has fraction: join remaining parts with /
                    displayVal += ' ' + parts.slice(1).join('/');
                }
                bodyContent.append('<div class="option-box" data-value="' + val + '">' + displayVal + '</div>');
            });
        } else {
            bodyContent.append('<div class="option-box" style="color: #888;">Select GAP first</div>');
        }

        // Trigger the group check after population
        setTimeout(function() {
            checkGroupComplete('sp');
        }, 100);
    });

    // Listen to all option-box clicks for group completion check
    $(document).on('click', '.option-box', function() {
        var $this = $(this);
        var header = $this.closest('.profile-accordion-content').prev('.profile-accordion-header');
        var group = header.data('group');

        console.log('HA Option clicked, group:', group);

        if (group) {
            setTimeout(function() {
                checkGroupComplete(group);
            }, 150);
        }
    });

    // Privacy: Populate BODY based on WIDTH selection (same values for both 6' and 8')
    $(document).on('click', '.pr-width-option', function(e) {
        var widthValue = $(this).data('value');
        var bodyContent = $('.pr-body-content');

        console.log('Privacy WIDTH selected:', widthValue);

        // Same BODY values for both 6' and 8' widths
