        // Trigger the group check after population
        setTimeout(function() {
            checkGroupComplete('mix');
        }, 100);
    });

    // Handle View Image and Download buttons for all groups
    $(document).on('click', '.view-image', function() {
        var $btn = $(this);
        var filterGroup = $btn.data('filter-group');
        var catId = $btn.data('cat-id');
        var btnName = $btn.data('btn-name');

        console.log('Button clicked:', filterGroup, catId, btnName);

        // Get selected values based on group
        var filters = {};
        var headerSelectors = '';
        
        if (filterGroup === 'sp') {
            headerSelectors = '.sp-gap-header, .sp-width-header, .sp-body-header';
        } else if (filterGroup === 'pr') {
            headerSelectors = '.pr-width-header, .pr-body-header';
        } else if (filterGroup === 'mix') {
            headerSelectors = '.mix-rail-header, .mix-width-header, .mix-body-header';
        }

        // Collect all selected filter values
        var allSelected = true;
        $(headerSelectors).each(function() {
            var filterKey = $(this).data('filter-key');
            var selectedVal = $(this).next('.profile-accordion-content').find('.option-box.selected').data('value');
            
            if (selectedVal) {
                filters[filterKey] = selectedVal;
                console.log('Filter:', filterKey, '=', selectedVal);
            } else {
                allSelected = false;
                console.log('Missing selection for:', filterKey);
            }
        });

        if (!allSelected) {
            alert('Please select all required options');
            return;
        }

        // Build AJAX request to fetch PDF
        var ajaxData = {
            action: 'get_profile_pdf',
            category_id: catId,
            filters: filters
        };

        console.log('Sending AJAX request:', ajaxData);

        $.ajax({
            url: '/wp-admin/admin-ajax.php',
            type: 'POST',
            data: ajaxData,
            success: function(response) {
                console.log('AJAX Response:', response);
                
                try {
                    var data = typeof response === 'string' ? JSON.parse(response) : response;
                    
                    if (data.success && data.pdf_url) {
                        if (btnName === 'vi') {
                            // View Image - Open in modal or new window
                            window.open(data.pdf_url, '_blank');
                            console.log('Opening PDF:', data.pdf_url);
                        } else if (btnName === 'dwn') {
                            // Download - Force download
                            var link = document.createElement('a');
                            link.href = data.pdf_url;
                            link.download = data.pdf_name || 'profile.pdf';
                            document.body.appendChild(link);
                            link.click();
                            document.body.removeChild(link);
                            console.log('Downloading PDF:', data.pdf_url);
                        }
                    } else {
                        alert('PDF not found for the selected options');
                        console.log('PDF not found. Response:', data);
                    }
                } catch(e) {
                    console.error('Error parsing response:', e);
                    alert('Error retrieving PDF');
                }
            },
            error: function(xhr, status, error) {
                console.error('AJAX Error:', error);
                alert('Error retrieving PDF. Please try again.');
            }
        });
    });

    // Add selection styling - toggle selected class on click
    $(document).on('click', '.option-box', function() {
        var $this = $(this);
        var $container = $this.closest('.profile-accordion-content');
        
        // Remove selected from all in this container
        $container.find('.option-box').removeClass('selected');
        
        // Add selected to clicked item
        $this.addClass('selected');
        
        console.log('Option selected:', $this.data('value'), 'in', $this.closest('.profile-section').find('.profile-accordion-header[data-group]').data('group'));
    });

    // Auto-populate on page load (select popular options)
    setTimeout(function() {
        // Trigger GAP=1 for Semi-Privacy
        $('.sp-gap-header + .profile-accordion-content .option-box[data-value="1"]').trigger('click');

        // Trigger WIDTH=6 for Privacy
